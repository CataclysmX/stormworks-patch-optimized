#!/usr/bin/env python3
"""Generates src/opengl32_thunks.S and src/opengl32.def from src/opengl32.exports.
Every export jumps through a slot; slots start on a per-function stub that calls gl_resolve()."""
names = [l.strip() for l in open("src/opengl32.exports") if l.strip()]
s = ['/* generated by tools_gen_gl.py: lazy forwarding of opengl32 to System32\\opengl32.dll */',
     '    .text']
for n in names:
    s += [f'    .globl {n}', f'{n}:', f'    jmp *slot_{n}(%rip)']
for n in names:
    s += [f'lazy_{n}:', f'    leaq name_{n}(%rip), %r10', f'    leaq slot_{n}(%rip), %r11', '    jmp gl_lazy_common']
s += ['''
/* r10 = name, r11 = slot. Saves the argument registers (rcx rdx r8 r9 xmm0-3), resolves, restores,
 * then jumps to the real function with the caller's stack untouched. Entry rsp = 8 mod 16. */
gl_lazy_common:
    subq $0x98, %rsp
    movq %rcx, 0x20(%rsp)
    movq %rdx, 0x28(%rsp)
    movq %r8, 0x30(%rsp)
    movq %r9, 0x38(%rsp)
    movdqu %xmm0, 0x40(%rsp)
    movdqu %xmm1, 0x50(%rsp)
    movdqu %xmm2, 0x60(%rsp)
    movdqu %xmm3, 0x70(%rsp)
    movq %r10, %rcx
    movq %r11, %rdx
    call gl_resolve
    movq 0x20(%rsp), %rcx
    movq 0x28(%rsp), %rdx
    movq 0x30(%rsp), %r8
    movq 0x38(%rsp), %r9
    movdqu 0x40(%rsp), %xmm0
    movdqu 0x50(%rsp), %xmm1
    movdqu 0x60(%rsp), %xmm2
    movdqu 0x70(%rsp), %xmm3
    addq $0x98, %rsp
    jmp *%rax
''', '    .data', '    .p2align 3']
for n in names:
    s += [f'slot_{n}: .quad lazy_{n}']
s += ['    .section .rdata,"dr"']
for n in names:
    s += [f'name_{n}: .asciz "{n}"']
open("src/opengl32_thunks.S", "w").write("\n".join(s) + "\n")
open("src/opengl32.def", "w").write("LIBRARY opengl32.dll\nEXPORTS\n" + "".join(f"  {n}\n" for n in names))
